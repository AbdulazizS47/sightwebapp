// CMO Office tables. Kept free of imports so db.js can run them inside initSchema().
export const CMO_OFFICE_TABLES = [
  `CREATE TABLE IF NOT EXISTS cmo_assets (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    chatId VARCHAR(32) NOT NULL,
    telegramFileId VARCHAR(255) NOT NULL,
    telegramFileUniqueId VARCHAR(128) NULL,
    kind VARCHAR(16) NOT NULL,
    fileName VARCHAR(255) NULL,
    mimeType VARCHAR(128) NULL,
    byteSize INT UNSIGNED NULL,
    data LONGBLOB NULL,
    title VARCHAR(255) NULL,
    assetType VARCHAR(32) NULL,
    description TEXT NULL,
    tags JSON NULL,
    language VARCHAR(16) NULL,
    menuItems JSON NULL,
    campaign VARCHAR(255) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    uploadedByUserId VARCHAR(32) NULL,
    uploadedByName VARCHAR(255) NULL,
    createdAt BIGINT NOT NULL,
    updatedAt BIGINT NOT NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cmo_messages (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    chatId VARCHAR(32) NOT NULL,
    telegramMessageId BIGINT NULL,
    direction VARCHAR(8) NOT NULL,
    fromUserId VARCHAR(32) NULL,
    fromName VARCHAR(255) NULL,
    messageType VARCHAR(16) NOT NULL,
    text MEDIUMTEXT NULL,
    assetId BIGINT NULL,
    replyToTelegramMessageId BIGINT NULL,
    createdAt BIGINT NOT NULL,
    UNIQUE KEY uq_cmo_messages_chat_message_direction (chatId, telegramMessageId, direction),
    FOREIGN KEY (assetId) REFERENCES cmo_assets(id) ON DELETE SET NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cmo_brand_notes (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    category VARCHAR(32) NOT NULL,
    note TEXT NOT NULL,
    source VARCHAR(16) NOT NULL DEFAULT 'chat',
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    starterKey VARCHAR(64) NULL,
    createdByUserId VARCHAR(32) NULL,
    createdByName VARCHAR(255) NULL,
    createdAt BIGINT NOT NULL,
    updatedAt BIGINT NOT NULL,
    UNIQUE KEY uq_cmo_brand_notes_starter (starterKey)
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cmo_proposals (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    batchId BIGINT NULL,
    proposalType VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    platform VARCHAR(32) NULL,
    scheduledDate VARCHAR(10) NULL,
    scheduledTime VARCHAR(5) NULL,
    assetId BIGINT NULL,
    title VARCHAR(255) NULL,
    captionAr TEXT NULL,
    captionEn TEXT NULL,
    hashtags TEXT NULL,
    rationale TEXT NULL,
    visualBrief TEXT NULL,
    sourceMessageId BIGINT NULL,
    createdByName VARCHAR(255) NULL,
    reviewedByUserId VARCHAR(32) NULL,
    reviewedByName VARCHAR(255) NULL,
    reviewedAt BIGINT NULL,
    approvalTelegramMessageId BIGINT NULL,
    createdAt BIGINT NOT NULL,
    updatedAt BIGINT NOT NULL,
    FOREIGN KEY (assetId) REFERENCES cmo_assets(id) ON DELETE SET NULL,
    FOREIGN KEY (sourceMessageId) REFERENCES cmo_messages(id) ON DELETE SET NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
];

export const CMO_OFFICE_INDEXES = [
  'CREATE INDEX idx_cmo_messages_chat_created ON cmo_messages(chatId, createdAt)',
  'CREATE INDEX idx_cmo_assets_status_type ON cmo_assets(status, assetType)',
  'CREATE INDEX idx_cmo_proposals_status_date ON cmo_proposals(status, scheduledDate)',
  'CREATE INDEX idx_cmo_proposals_batch ON cmo_proposals(batchId)',
  'CREATE INDEX idx_cmo_proposals_approval_message ON cmo_proposals(approvalTelegramMessageId)',
];
