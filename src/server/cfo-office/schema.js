// CFO Office tables. Kept free of imports so db.js can run them inside initSchema().
export const CFO_OFFICE_TABLES = [
  `CREATE TABLE IF NOT EXISTS cfo_members (
    telegramUserId VARCHAR(32) PRIMARY KEY,
    displayName VARCHAR(255) NOT NULL,
    username VARCHAR(64) NULL,
    role VARCHAR(64) NULL,
    notes TEXT NULL,
    isApprover TINYINT(1) NOT NULL DEFAULT 0,
    firstSeenAt BIGINT NOT NULL,
    lastSeenAt BIGINT NOT NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cfo_attachments (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    chatId VARCHAR(32) NOT NULL,
    telegramFileId VARCHAR(255) NOT NULL,
    telegramFileUniqueId VARCHAR(128) NULL,
    kind VARCHAR(16) NOT NULL,
    fileName VARCHAR(255) NULL,
    mimeType VARCHAR(128) NULL,
    byteSize INT UNSIGNED NULL,
    data MEDIUMBLOB NULL,
    createdAt BIGINT NOT NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cfo_messages (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    chatId VARCHAR(32) NOT NULL,
    telegramMessageId BIGINT NULL,
    direction VARCHAR(8) NOT NULL,
    fromUserId VARCHAR(32) NULL,
    fromName VARCHAR(255) NULL,
    messageType VARCHAR(16) NOT NULL,
    text MEDIUMTEXT NULL,
    attachmentId BIGINT NULL,
    replyToTelegramMessageId BIGINT NULL,
    questionKey VARCHAR(64) NULL,
    createdAt BIGINT NOT NULL,
    UNIQUE KEY uq_cfo_messages_chat_message_direction (chatId, telegramMessageId, direction),
    FOREIGN KEY (attachmentId) REFERENCES cfo_attachments(id) ON DELETE SET NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cfo_questions (
    questionKey VARCHAR(64) PRIMARY KEY,
    topic VARCHAR(32) NOT NULL,
    audience VARCHAR(16) NOT NULL DEFAULT 'any',
    priority INT NOT NULL DEFAULT 100,
    questionEn TEXT NOT NULL,
    questionAr TEXT NULL,
    source VARCHAR(16) NOT NULL DEFAULT 'starter',
    status VARCHAR(16) NOT NULL DEFAULT 'open',
    timesAsked INT NOT NULL DEFAULT 0,
    lastAskedAt BIGINT NULL,
    answeredAt BIGINT NULL,
    answerSummary TEXT NULL,
    createdAt BIGINT NOT NULL,
    updatedAt BIGINT NOT NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  `CREATE TABLE IF NOT EXISTS cfo_records (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    recordType VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    recordDate VARCHAR(10) NULL,
    description TEXT NOT NULL,
    category VARCHAR(64) NULL,
    counterparty VARCHAR(255) NULL,
    amount DECIMAL(12,2) NULL,
    vatAmount DECIMAL(12,2) NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'SAR',
    quantity DECIMAL(12,3) NULL,
    unit VARCHAR(32) NULL,
    unitCost DECIMAL(12,4) NULL,
    frequency VARCHAR(16) NULL,
    paymentMethod VARCHAR(32) NULL,
    inventoryItemId VARCHAR(64) NULL,
    staffMemberName VARCHAR(255) NULL,
    questionKey VARCHAR(64) NULL,
    details JSON NULL,
    sourceMessageId BIGINT NULL,
    attachmentId BIGINT NULL,
    submittedByUserId VARCHAR(32) NULL,
    submittedByName VARCHAR(255) NULL,
    reviewedByUserId VARCHAR(32) NULL,
    reviewedByName VARCHAR(255) NULL,
    reviewedAt BIGINT NULL,
    approvalTelegramMessageId BIGINT NULL,
    createdAt BIGINT NOT NULL,
    updatedAt BIGINT NOT NULL,
    FOREIGN KEY (sourceMessageId) REFERENCES cfo_messages(id) ON DELETE SET NULL,
    FOREIGN KEY (attachmentId) REFERENCES cfo_attachments(id) ON DELETE SET NULL
  ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
];

export const CFO_OFFICE_INDEXES = [
  'CREATE INDEX idx_cfo_messages_chat_created ON cfo_messages(chatId, createdAt)',
  'CREATE INDEX idx_cfo_records_type_date ON cfo_records(recordType, recordDate)',
  'CREATE INDEX idx_cfo_records_status_created ON cfo_records(status, createdAt)',
  'CREATE INDEX idx_cfo_records_approval_message ON cfo_records(approvalTelegramMessageId)',
  'CREATE INDEX idx_cfo_questions_status_priority ON cfo_questions(status, priority)',
];
